const assert = require("node:assert/strict"), fs = require("node:fs"), vm = require("node:vm");
let rows = [], metadata = { "@type": "Product", name: "ДСП", sku: "33943" };
const node = value => ({ textContent: value, getClientRects: () => [1], closest: () => null });
const document = {
  querySelectorAll: selector => selector.includes("application/ld+json") ? [{ textContent: JSON.stringify(metadata) }] : selector === "tr, li, div, p, dd" ? rows : [],
  querySelector: selector => selector === "h1" ? node("ДСП") : selector === ".width" ? node("2070") : selector === ".thickness-select" ? { tagName: "SELECT", value: "thickness-id", selectedOptions: [node("18")], textContent: "161822" } : null
};
const context = { document, location: { hostname: "shop.example" } };
vm.createContext(context);
for (const path of ["core/formatter.js", "core/parser.js"]) vm.runInContext(fs.readFileSync(path, "utf8"), context);
const f = context.YSCFormatter, p = context.YSCParser;
assert.equal(f.dimensionMetres("2800"), "2,8");
assert.equal(f.dimensionMetres("2,07", "m"), "2,07");
assert.equal(f.dimensionMetres("Довжина, мм 2800"), "2,8");
assert.equal(f.dimensionMetres("2070 мм", "m"), "2,07");
assert.equal(f.dimensionMetres("Довжина, м 2,8"), "2,8");
assert.equal(f.thicknessMm("Товщина, мм 18"), "18");
assert.equal(f.thicknessMm("0,018 м"), "18");
assert.equal(f.thicknessMm("18,5"), "18,5");
assert.equal(f.thicknessMm("18/22"), "");
for (const bad of ["", "0", "-2800", "2800*2070", "2800 2070", "2800 см", "NaN"]) assert.equal(f.dimensionMetres(bad), "");
const fields = { supplier: "VIYAR", article: "33943", name: "ДСП", unit: "лист", sheetLength: "2800", sheetWidth: "2070", price: "6577.02" };
assert.equal(f.sheetSize(fields), "(2,8*2,07)");
const rodFields = { ...fields, unit: "пог.м", sheetLength: "5950.00мм", sheetWidth: "", sheetThickness: "18" };
assert.equal(f.sheetSize(rodFields, { sheetRod: true }), "(5,95)");
assert.equal(f.sheetUnit(rodFields, { sheet: true, sheetRod: true }), "пог.м (5,95)");
assert.equal(f.sheetSize({ ...rodFields, sheetWidth: "123" }, { sheetRod: true }), "(5,95)");
assert.equal(f.sheetSize({ ...rodFields, sheetLength: "" }, { sheetRod: true }), "");
assert.equal(f.sheetSize(rodFields, { sheet: true }), "");
assert.equal(f.format(rodFields, { sheet: true, sheetRod: true }), "VIYAR 33943 ДСП");
assert.equal(f.formatExcel(fields, { sheet: true }), "VIYAR 33943 ДСП\tлист (2,8*2,07)\t6577,02");
assert.equal(f.formatExcel(fields), "VIYAR 33943 ДСП\tлист\t6577,02");
assert.equal(f.format(fields, { sheet: true }), "VIYAR 33943 ДСП");
fields.sheetThickness = "18";
assert.equal(f.format(fields, { sheet: true }), "VIYAR 33943 ДСП - 18");
assert.equal(f.formatExcel(fields, { sheet: true }), "VIYAR 33943 ДСП - 18\tлист (2,8*2,07)\t6577,02");
assert.equal(f.format(fields), "VIYAR 33943 ДСП");
assert.equal(f.format(fields, { sheet: true, name: false }), "VIYAR 33943");
rows = [node("Довжина, мм 2800"), node("Ширина, мм 2070"), node("Товщина, мм 18"), node("Висота, мм 900")];
let parsed = p.parse({ format: { sheet: true } });
assert.equal(parsed.sheetLength, "2800 мм"); assert.equal(parsed.sheetWidth, "2070 мм");
assert.equal(parsed.sheetThickness, "18");
assert.equal(f.sheetSize(parsed), "(2,8*2,07)");
parsed = p.parse({ format: { sheet: true }, fields: { sheetWidth: { enabled: true, source: "css", selector: ".width" } } });
assert.equal(parsed.sheetWidth, "2070");
parsed = p.parse({ format: { sheet: true }, fields: { sheetThickness: { enabled: true, source: "css", selector: ".thickness-select" } } });
assert.equal(parsed.sheetThickness, "18", "Select picker reads only selected option, not all thicknesses");
rows = [];
metadata.additionalProperty = [{ name: "Довжина, мм", value: 2800 }, { name: "Ширина", value: 2.07, unitText: "m" }, { name: "Товщина", value: 0.018, unitText: "m" }];
parsed = p.parse({ format: { sheet: true } });
assert.equal(f.sheetSize(parsed), "(2,8*2,07)");
assert.equal(parsed.sheetThickness, "18");
assert.equal(p.parse().sheetLength, "");
console.log("Sheet dimensions: parsing, selection, metre conversion and unit-only Excel output passed");
